// مولد رسائل الواتساب الذكية للمدير
export const buildWhatsAppMessage = (
  type: 'midterm_reminder' | 'final_reminder' | 'eval_result' | 'custom' | 'ready_notification',
  teacherName: string,
  principalName: string,
  roleTitle: string,
  extraData?: {
    deadline?: string;
    totalScore?: number;
    gradeLabel?: string;
    comments?: string;
    customText?: string;
  }
) => {
  let message = `الأستاذ الفاضل / ${teacherName} (${roleTitle})\nثانوية الأمير عبدالمجيد الأولى\n\n`;

  if (type === 'midterm_reminder') {
    message += `تحية طيبة،\nنود تذكيركم ببدء فترة رصد **المراجعة نصف السنوية للأداء الوظيفي**.\nنأمل التكرم بالدخول على منصة إتقان وتزويدنا برابط مجلد الشواهد الرقمي الخاص بكم قبل تاريخ: ${extraData?.deadline || 'الموعد المحدد'}.\n\nشاكرين ومقدرين جهودكم المتميزة.\nمدير المدرسة: ${principalName}`;
  } else if (type === 'final_reminder') {
    message += `تحية طيبة،\nنود إشعاركم ببدء مرحلة **التقييم النهائي للأداء الوظيفي** للعام الدراسي.\nيرجى استكمال وتحديث ملف شواهدكم الختامي عبر منصة إتقان للاعتماد النهائي.\n\nمدير المدرسة: ${principalName}`;
  } else if (type === 'eval_result') {
    const pointsFrom5 = extraData?.totalScore ? (extraData.totalScore / 20).toFixed(2) : '5.00';
    message += `نبارك لكم اعتماد تقييم الأداء الوظيفي السنوي:\n- التقدير العام: *${extraData?.gradeLabel || 'مثالي'}*\n- المعدل الموزون: *${pointsFrom5} من 5* (${extraData?.totalScore}%)\n`;
    if (extraData?.comments) {
      message += `- توصيات الإدارة: "${extraData.comments}"\n`;
    }
    message += `\nسائلين الله لكم دوام التوفيق والتميز.\nمدير المدرسة: ${principalName}`;
  } else if (type === 'custom') {
    message += `${extraData?.customText || ''}\n\nمدير المدرسة: ${principalName}`;
  }

  return encodeURIComponent(message);
};
